#!/usr/bin/env python3
"""Builds every captain's story into the game data.

    python3 tools/stories/build.py

Reads the story modules in this folder (one per captain), writes datafiles/data/campaign.json, adds or updates
their items, characters and boss ships in items.json, characters.json and ships.json, and merges the Spanish
side of every text into lang/es.json. Edit the stories here, never campaign.json directly.
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
DATA = os.path.join(HERE, "..", "..", "game", "ExchangeTides", "datafiles", "data")
import sk
import vega, wren, calder, moreno, quill, bale
import extras

ORDER = [vega, wren, calder, moreno, quill, bale]          # campaign.json order (Vega's story first)
CAPTAIN = {"vega": "grimmer_debt", "wren": "bad_powder", "calder": "second_seal",
           "moreno": "turncoat", "quill": "compact", "bale": "false_light"}

def load(name): return json.load(open(os.path.join(DATA, name), encoding="utf-8"))
def save(name, obj): json.dump(obj, open(os.path.join(DATA, name), "w", encoding="utf-8"), indent=1, ensure_ascii=False)

def upsert(lst, new):
    idx = {x["id"]: i for i, x in enumerate(lst)}
    for n in new:
        if n["id"] in idx: lst[idx[n["id"]]] = n
        else: idx[n["id"]] = len(lst); lst.append(n)

def main():
    extras.apply([m.STORY for m in ORDER])
    save("campaign.json", {"_doc": "Generated by tools/stories/build.py from the story modules; edit those instead. Canon: docs/STORIES.md.",
                           "campaigns": [m.STORY for m in ORDER]})
    items = load("items.json"); upsert(items, sk.ITEMS); save("items.json", items)
    ships = load("ships.json"); upsert(ships["enemies"], sk.ENEMIES); save("ships.json", ships)
    chars = load("characters.json")
    for c in chars["captains"]: c["campaign"] = CAPTAIN[c["id"]]
    seen = {}
    for n in sk.NPCS: seen[n["id"]] = n
    upsert(chars["npcs"], list(seen.values())); save("characters.json", chars)
    es = load(os.path.join("lang", "es.json")); es.update(sk.ES); save(os.path.join("lang", "es.json"), es)
    for m in ORDER:
        st = m.STORY
        steps = [s for ch in st["chapters"] for s in ch["steps"]]
        print(f'{st["id"]:14} {len(st["chapters"])} chapters, {sum(1 for s in steps if s["do"] == "goal")} goals, '
              f'{sum(1 for s in steps if s["do"] == "say")} dialogues')
    print(len(sk.ES), "Spanish texts merged")

if __name__ == "__main__":
    main()
